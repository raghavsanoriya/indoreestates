import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const output=path.join(root,'output/browser');
const base=process.env.E2E_BASE_URL||'http://127.0.0.1:8003';
assert.ok(process.env.E2E_AGENT_EMAIL && process.env.E2E_AGENT_PASSWORD,'Set E2E_AGENT_EMAIL and E2E_AGENT_PASSWORD for an isolated local test account.');
assert.ok(['127.0.0.1','localhost'].includes(new URL(base).hostname),'This test creates disposable data and must run locally.');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
page.setDefaultTimeout(10000);
page.setDefaultNavigationTimeout(20000);
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('response',response=>{if(response.url().startsWith(base)&&response.status()>=500){errors.push(response.status()+' '+response.url());}});
const title='QA Playwright Add Property '+Date.now();
const checks=[];
let propertyId;
try{
    await page.goto(base+'/dashboard/properties/create',{waitUntil:'domcontentloaded'});
    await page.getByLabel('Email address',{exact:true}).fill(process.env.E2E_AGENT_EMAIL);
    await page.getByLabel('Password',{exact:true}).fill(process.env.E2E_AGENT_PASSWORD);
    await page.getByRole('button',{name:'Sign in ↗',exact:true}).click();
    await page.waitForURL(/\/dashboard/);
    await page.goto(base+'/dashboard/properties/create',{waitUntil:'domcontentloaded'});
    assert.equal(await page.locator('main section h2').count(),9);
    assert.equal(await page.getByRole('heading',{name:'Upload Media',exact:true}).isVisible(),true);
    assert.equal(await page.locator('.reference-sidebar').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(22, 30, 45)');
    assert.equal(await page.locator('[name="title"]').evaluate(el=>getComputedStyle(el).borderRadius),'99px');
    await page.screenshot({path:path.join(output,'add-property-desktop.jpg'),fullPage:true,type:'jpeg',quality:75,timeout:15000});
    await page.screenshot({path:path.join(output,'add-property-desktop-preview.jpg'),type:'jpeg',quality:85,timeout:15000});
    checks.push('Nine reference sections, dark sidebar and rounded input styling');

    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await page.waitForFunction(()=>document.querySelector('.reference-sidebar').getBoundingClientRect().right<=0);
    await page.getByRole('button',{name:'Toggle dashboard sidebar',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.reference-sidebar').getBoundingClientRect().right>0);
    await page.keyboard.press('Escape');
    await page.waitForFunction(()=>document.querySelector('.reference-sidebar').getBoundingClientRect().right<=0);
    await page.screenshot({path:path.join(output,'add-property-mobile.jpg'),fullPage:true,type:'jpeg',quality:75,timeout:15000});
    await page.screenshot({path:path.join(output,'add-property-mobile-preview.jpg'),type:'jpeg',quality:85,timeout:15000});
    checks.push('390px mobile layout without horizontal overflow; sidebar opens and closes');
    await page.setViewportSize({width:1440,height:1000});

    await page.locator('#photo-uploads').setInputFiles([1,2,3].map(id=>path.join(root,'public/template/images/home/house-'+id+'.jpg')));
    await page.getByRole('status').filter({hasText:'3 new photo(s) selected.'}).waitFor();
    assert.equal(await page.locator('#upload-preview img').count(),3);
    await page.getByLabel('Title: *',{exact:true}).fill(title);
    await page.getByLabel('Description: *',{exact:true}).fill('Disposable browser-test listing for the converted Add Property UI.');
    await page.getByLabel('Full Address: *',{exact:true}).fill('12 Sample QA Road');
    await page.getByLabel('Location / City: *',{exact:true}).fill('Pune');
    await page.getByLabel('Price (₹): *',{exact:true}).fill('7500000');
    await page.getByLabel('Size (SqFt): *',{exact:true}).fill('1800');
    await page.getByLabel('Rooms: *',{exact:true}).fill('5');
    await page.getByLabel('Bedrooms: *',{exact:true}).fill('3');
    await page.getByLabel('Bathrooms: *',{exact:true}).fill('2');
    await page.getByLabel('Garages: *',{exact:true}).fill('1');
    await page.getByRole('checkbox',{name:'Smoke alarm',exact:true}).check();
    await page.getByRole('radio',{name:'Enable',exact:true}).check();
    await page.getByLabel('Floor Name: *',{exact:true}).fill('Ground floor QA');
    await page.getByLabel('Floor Size:',{exact:true}).fill('900');
    await page.getByLabel('Floor Image:',{exact:true}).setInputFiles(path.join(root,'public/template/images/banner/floor.png'));
    await page.getByRole('button',{name:'＋ Add floor',exact:true}).click();
    assert.equal(await page.locator('#floor-list .floor-card').count(),2);
    await page.getByRole('button',{name:'Remove floor plan',exact:true}).nth(1).click();
    assert.equal(await page.locator('#floor-list .floor-card').count(),1);
    await page.getByRole('radio',{name:'Other contact',exact:true}).check();
    await page.getByLabel('Contact name:',{exact:true}).fill('QA Contact');
    await page.getByLabel('Contact email:',{exact:true}).fill('qa@example.test');
    await page.getByRole('button',{name:'Save & Preview',exact:true}).click();
    await page.waitForURL(/\/dashboard\/properties\/\d+\/preview$/);
    propertyId=page.url().match(/\/properties\/(\d+)\/preview$/)[1];
    assert.ok(await page.getByText('Private preview · Draft · Available',{exact:true}).isVisible());
    assert.equal(await page.getByRole('heading',{name:title,exact:true}).isVisible(),true);
    assert.equal(await page.getByRole('img',{name:'Ground floor QA floor plan',exact:true}).count(),1);
    assert.equal(await page.getByRole('heading',{name:'QA Contact',exact:true}).isVisible(),true);
    const photoUrl=await page.locator('.detail-gallery img').first().getAttribute('src');
    const guest=await browser.newContext();
    assert.equal((await guest.request.get(base+'/properties/'+propertyId)).status(),404);
    assert.equal((await guest.request.get(photoUrl)).status(),404);
    await guest.close();
    checks.push('Three photos and floor image save; preview includes saved floor and contact; guests cannot access draft or its images');

    await page.goto(base+'/dashboard/properties/'+propertyId+'/edit',{waitUntil:'domcontentloaded'});
    assert.equal(await page.getByLabel('Title: *',{exact:true}).inputValue(),title);
    assert.equal(await page.getByLabel('Floor Name: *',{exact:true}).inputValue(),'Ground floor QA');
    assert.equal(await page.locator('.existing-property-photos img').count(),3);
    await page.getByRole('radio',{name:'Cover photo',exact:true}).nth(1).check();
    await page.getByRole('checkbox',{name:'Remove photo',exact:true}).first().check();
    await page.getByRole('button',{name:'Update Property',exact:true}).click();
    await page.waitForURL(base+'/dashboard/properties');
    let row=page.getByRole('row').filter({hasText:title});
    assert.ok((await row.innerText()).toLowerCase().includes('pending'));
    await row.getByRole('link',{name:'Edit',exact:true}).click();
    await page.waitForURL(new RegExp('/dashboard/properties/'+propertyId+'/edit$'),{waitUntil:'domcontentloaded'});
    await page.locator('.existing-property-photos img').nth(1).waitFor({state:'attached'});
    assert.equal(await page.locator('.existing-property-photos img').count(),2);
    assert.equal(await page.getByLabel('Floor Name: *',{exact:true}).inputValue(),'Ground floor QA');
    await page.screenshot({path:path.join(output,'add-property-saved-edit.jpg'),fullPage:true,type:'jpeg',quality:75,timeout:15000});
    checks.push('Editing restores saved fields, removes a photo, changes cover and submits listing as pending');

    await page.goto(base+'/dashboard/properties',{waitUntil:'domcontentloaded'});
    row=page.getByRole('row').filter({hasText:title});
    page.once('dialog',dialog=>dialog.accept());
    await row.getByRole('button',{name:'Trash',exact:true}).click();
    await page.waitForURL(base+'/dashboard/properties');
    assert.ok((await page.getByRole('row').filter({hasText:title}).innerText()).includes('Trashed'));
    checks.push('Disposable browser-test listing moved to recoverable trash');
    assert.deepEqual(errors,[]);
    checks.push('No browser JavaScript errors or local HTTP 5xx responses');
    await fs.writeFile(path.join(output,'add-property-results.json'),JSON.stringify({passed:true,checks,propertyId,screenshots:['add-property-desktop.jpg','add-property-mobile.jpg','add-property-saved-edit.jpg']},null,2));
    console.log(JSON.stringify({passed:true,checks,propertyId,output}));
}catch(error){
    await page.screenshot({path:path.join(output,'add-property-failure.jpg'),fullPage:true,type:'jpeg',quality:75,timeout:10000}).catch(()=>{});
    console.error(error);
    console.error(JSON.stringify({passed:false,propertyId,url:page.url(),errors}));
    process.exitCode=1;
}finally{
    await context.close();
    await browser.close();
}
